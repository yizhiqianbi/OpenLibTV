function actualGraphFixture() {
  const original = graphFixture(),
    currentDocument = { current: original };
  let actionsApi,
    deletionApi,
    draftsApi,
    props = { documentKey: 'A', ready: true, readonly: false };
  const onAccepted = vi.fn(),
    notify = vi.fn(),
    capture = vi.fn(() => deletionApi.capture()),
    createWriter = vi.fn(() => deletionApi.createWriter());
  const consumed = vi.fn(),
    projection = { fail: false, drift: false },
    pending = { writable: true, basePrompt: 'saved', value: 'first latest input' };
  const deleteEdges = vi.fn((ids, options) => actionsApi.deleteEdges(ids, options));
  const unlinkStoryboardEdges = vi.fn((ids, options) =>
    actionsApi.unlinkStoryboardEdges(ids, options),
  );
  const deleteNodes = vi.fn((ids, options) =>
    Promise.resolve().then(() =>
      options.canCommit() ? actionsApi.deleteNodes(ids, options) : false,
    ),
  );
  const hook = renderHook(
    (value) => {
      const [nodes, setNodes] = useState(original.nodes),
        [edges, setEdges] = useState(original.edges);
      const history = useSnapshotHistory(
        { nodes, edges },
        {
          restore(next) {
            currentDocument.current = { ...currentDocument.current, ...next };
            setNodes(next.nodes);
            setEdges(next.edges);
          },
        },
      );
      const drafts = useCanvasDrafts({ storageKey: value.documentKey, nodes, ready: value.ready });
      draftsApi = drafts;
      const deletion = useCanvasDeletionHistory({
        ...value,
        recordSnapshot: history.recordSnapshot,
        captureSnapshot: () => actionsApi.captureDeletionSnapshot(),
        notify,
      });
      deletionApi = deletion;
      const actions = useCanvasGraphActions({
        documentKey: value.documentKey,
        currentDocument,
        setNodes,
        setEdges,
        notify,
        recordSnapshot: deletion.recordSnapshot,
        projectGraph(graph, options) {
          if (projection.fail) {
            projection.fail = false;
            throw new Error('draft read');
          }
          const next = drafts.project({ ...graph, storageKey: value.documentKey }, options);
          if (projection.drift) {
            projection.drift = false;
            currentDocument.current = {
              ...currentDocument.current,
              edges: [...currentDocument.current.edges],
            };
          }
          return next;
        },
        consumeDrafts(graph, options) {
          consumed(graph, options);
          drafts.consume({ ...graph, storageKey: value.documentKey }, options);
        },
      });
      actionsApi = actions;
      const deletionController = useCanvasSelectedDeletion({
        ...value,
        history: { capture, createWriter },
        getDocument: () => currentDocument.current,
        deleteEdges,
        deleteNodes,
        unlinkStoryboardEdges,
        disconnectClip: vi.fn(),
        notify,
        onAccepted,
        zoom: 0.8,
      });
      return { controller: deletionController, history, drafts, deletion };
    },
    { initialProps: props },
  );
  draftsApi.register('A', 's', () => pending);
  return {
    ...hook,
    original,
    currentDocument,
    consumed,
    capture,
    createWriter,
    notify,
    onAccepted,
    projection,
    pending,
    deleteEdges,
    deleteNodes,
    unlinkStoryboardEdges,
    change(patch) {
      props = { ...props, ...patch };
      currentDocument.current = { ...currentDocument.current, ...patch };
      hook.rerender(props);
    },
  };
}
function withPrompt(graph, prompt) {
  return {
    nodes: graph.nodes.map((node) =>
      node.id === 's'
        ? { ...node, data: { ...node.data, params: { ...node.data.params, prompt } } }
        : node,
    ),
    edges: graph.edges,
  };
}

describe('selected coordinator with actual GraphActions, drafts and undo history', () => {
  it('ordinary stage survives association cancellation, and UI node microtask does not wait for the modal', async () => {
    const f = actualGraphFixture();
    act(() =>
      expect(
        f.result.current.controller.remove({ nodeIds: ['n'], edgeIds: ['o1', 'link1', 'link2'] }),
      ).toBe(true),
    );
    const request = f.result.current.controller.request;
    expect(request.stage).toBe('associations');
    expect(f.deleteNodes.mock.calls[0][1].ui).toBe(true);
    await flushJobs();
    const expected = withPrompt(f.original, 'first latest input');
    expected.nodes = expected.nodes.filter((node) => node.id !== 'n');
    expected.edges = expected.edges.filter((edge) => edge.id !== 'o1');
    expect(graphState(f.currentDocument.current)).toEqual(expected);
    expect(f.result.current.history.history.current).toEqual([
      withPrompt(f.original, 'first latest input'),
    ]);
    act(() => expect(f.result.current.controller.cancel(request)).toBe(true));
    expect(graphState(f.currentDocument.current)).toEqual(expected);
    expect(f.unlinkStoryboardEdges).not.toHaveBeenCalled();
    act(() => {
      f.result.current.deletion.flush();
      f.result.current.history.undo();
    });
    expect(graphState(f.currentDocument.current)).toEqual(
      withPrompt(f.original, 'first latest input'),
    );
    act(() => f.result.current.history.redo());
    expect(graphState(f.currentDocument.current)).toEqual(expected);
  });

  it('delayed association acceptance keeps last prompt, cohort order and two real undo/redo segments', async () => {
    const f = actualGraphFixture();
    act(() => expect(f.result.current.controller.removeEdges(['o1', 'link2', 'link1'])).toBe(true));
    const request = f.result.current.controller.request;
    const initial = withPrompt(f.original, 'first latest input'),
      ordinary = { ...initial, edges: initial.edges.filter((edge) => edge.id !== 'o1') };
    expect(graphState(f.currentDocument.current)).toEqual(ordinary);
    await flushJobs();
    f.pending.basePrompt = 'first latest input';
    f.pending.value = 'last 150ms input';
    const beforeAssociation = withPrompt(ordinary, 'last 150ms input');
    const after = {
      nodes: beforeAssociation.nodes.map((node) => {
        if (node.id === 's') {
          const { linkedImageGroupId: _link, ...data } = node.data;
          return { ...node, data };
        }
        if (node.id === 'g') {
          const { sourceScriptNodeId: _source, storyboardTitle: _title, ...data } = node.data;
          return { ...node, data };
        }
        return node;
      }),
      edges: beforeAssociation.edges.filter((edge) => !['link1', 'link2'].includes(edge.id)),
    };
    act(() => expect(f.result.current.controller.confirm(request)).toBe(true));
    expect(f.unlinkStoryboardEdges.mock.calls[0][0]).toEqual(['link2', 'link1']);
    expect(graphState(f.currentDocument.current)).toEqual(after);
    expect(f.result.current.history.history.current).toEqual([initial, beforeAssociation]);
    act(() => {
      f.result.current.deletion.flush();
      f.result.current.history.undo();
    });
    expect(graphState(f.currentDocument.current)).toEqual(beforeAssociation);
    act(() => f.result.current.history.undo());
    expect(graphState(f.currentDocument.current)).toEqual(initial);
    act(() => f.result.current.history.redo());
    expect(graphState(f.currentDocument.current)).toEqual(beforeAssociation);
    act(() => f.result.current.history.redo());
    expect(graphState(f.currentDocument.current)).toEqual(after);
  });

  it('binding drift rejects only the late association stage, retaining earlier ordinary graph/history', async () => {
    const f = actualGraphFixture();
    act(() => expect(f.result.current.controller.removeEdges(['o1', 'link1'])).toBe(true));
    const request = f.result.current.controller.request;
    await flushJobs();
    const ordinary = withPrompt(f.original, 'first latest input');
    ordinary.edges = ordinary.edges.filter((edge) => edge.id !== 'o1');
    f.currentDocument.current = {
      ...f.currentDocument.current,
      nodes: f.currentDocument.current.nodes.map((node) =>
        node.id === 'g'
          ? { ...node, data: { ...node.data, sourceScriptNodeId: 'different-owner' } }
          : node,
      ),
    };
    const drifted = graphState(f.currentDocument.current);
    act(() => expect(f.result.current.controller.confirm(request)).toBe(false));
    expect(f.result.current.controller.request).toBeNull();
    expect(graphState(f.currentDocument.current)).toEqual(drifted);
    expect(f.unlinkStoryboardEdges).not.toHaveBeenCalled();
    expect(f.result.current.history.history.current).toEqual([
      withPrompt(f.original, 'first latest input'),
    ]);
    expect(f.notify).toHaveBeenCalledWith('待删除内容或分镜关联已变化，请重新选择');
  });

  it.each(['projection-throw', 'capture-CAS-drift'])(
    'actual preflight failure keeps the same request, all drafts and no history, then retry succeeds (%s)',
    (failure) => {
      const f = actualGraphFixture();
      act(() => expect(f.result.current.controller.removeEdges(['link1', 'link2'])).toBe(false));
      const request = f.result.current.controller.request;
      f.projection[failure === 'projection-throw' ? 'fail' : 'drift'] = true;
      act(() => expect(f.result.current.controller.confirm(request)).toBe(false));
      expect(f.result.current.controller.request).toBe(request);
      expect(graphState(f.currentDocument.current)).toEqual(graphState(f.original));
      expect(f.pending.value).toBe('first latest input');
      expect(f.consumed).not.toHaveBeenCalled();
      expect(f.result.current.history.history.current).toEqual([]);
      act(() => expect(f.result.current.controller.confirm(request)).toBe(true));
      expect(f.result.current.controller.request).toBeNull();
      expect(f.currentDocument.current.edges.map((edge) => edge.id)).toEqual([
        'o1',
        'o2',
        'edit1',
        'edit2',
        'clip-edge',
      ]);
      expect(
        f.currentDocument.current.nodes.find((node) => node.id === 's').data.params.prompt,
      ).toBe('first latest input');
      expect(f.result.current.history.history.current).toEqual([
        withPrompt(f.original, 'first latest input'),
      ]);
    },
  );
});

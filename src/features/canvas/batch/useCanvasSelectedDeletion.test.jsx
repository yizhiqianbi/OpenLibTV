const graphState = (graph) => ({ nodes: graph.nodes, edges: graph.edges });
function deferred() {
  let resolve, reject;
  const promise = new Promise((accept, decline) => {
    resolve = accept;
    reject = decline;
  });
  return { promise, resolve, reject };
}
async function flushJobs() {
  await act(async () => {
    await Promise.resolve();
    await Promise.resolve();
  });
}

// An injected graph port tests synchronous acceptance vs asynchronous launch.
// The separate harness below uses actual GraphActions, draft and history hooks.
function portFixture({ wrapper, graph = graphFixture(), ...extra } = {}) {
  let current = graph,
    props;
  const trace = [],
    notify = vi.fn(),
    onAccepted = vi.fn();
  const history = {
    capture: vi.fn(() => {
      trace.push(['capture']);
      return true;
    }),
    createWriter: vi.fn(() => vi.fn()),
  };
  const deleteEdges = vi.fn((ids) => {
    trace.push(['ordinary', [...ids]]);
    current = { ...current, edges: current.edges.filter((edge) => !ids.includes(edge.id)) };
    return true;
  });
  const deleteNodes = vi.fn((ids, options) => {
    trace.push(['nodes', [...ids], options.ui]);
    if (!options.canCommit()) return false;
    current = {
      ...current,
      nodes: current.nodes.filter((node) => !ids.includes(node.id)),
      edges: current.edges.filter(
        (edge) => !ids.includes(edge.source) && !ids.includes(edge.target),
      ),
    };
    return true;
  });
  const unlinkStoryboardEdges = vi.fn((ids) => {
    trace.push(['associations', [...ids]]);
    current = { ...current, edges: current.edges.filter((edge) => !ids.includes(edge.id)) };
    return true;
  });
  const disconnectClip = vi.fn((ids) => {
    trace.push(['clip', [...ids]]);
    return Promise.resolve({ deletedEdgeIds: [] });
  });
  props = {
    documentKey: 'A',
    ready: true,
    readonly: false,
    zoom: 0.8,
    history,
    getDocument: () => current,
    deleteEdges,
    deleteNodes,
    unlinkStoryboardEdges,
    disconnectClip,
    notify,
    onAccepted,
    now: () => 500,
    ...extra,
  };
  const hook = renderHook((value) => useCanvasSelectedDeletion(value), {
    initialProps: props,
    wrapper,
  });
  return {
    ...hook,
    trace,
    notify,
    onAccepted,
    history,
    deleteEdges,
    deleteNodes,
    unlinkStoryboardEdges,
    disconnectClip,
    get graph() {
      return current;
    },
    set graph(value) {
      current = value;
    },
    change(patch) {
      props = { ...props, ...patch };
      hook.rerender(props);
    },
  };
}
function open(f, selection) {
  act(() => expect(f.result.current.remove(selection)).toBe(false));
  return f.result.current.request;
}
function noStage(f) {
  expect(f.history.capture).not.toHaveBeenCalled();
  expect(f.deleteEdges).not.toHaveBeenCalled();
  expect(f.deleteNodes).not.toHaveBeenCalled();
  expect(f.disconnectClip).not.toHaveBeenCalled();
  expect(f.unlinkStoryboardEdges).not.toHaveBeenCalled();
  expect(f.onAccepted).not.toHaveBeenCalled();
}

